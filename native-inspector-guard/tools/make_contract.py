"""Read the stock PE and recovered metadata; never load or execute the PE."""
import hashlib
import json
import pathlib
import struct

ROOT = pathlib.Path(__file__).resolve().parents[1]
APP = pathlib.Path(r"D:\opentrack\OpenTrack.app\OpenTrack.exe")
BANK = pathlib.Path(r"D:\opentrack\OTReverse\20261027-bank-v027-timetable-export")
SHA = "f1274d5c03ac7fe07196c999eb088e6de7414a1da55b0276d3956513c866f104"
SPECS = [
    ("OTInspector", "inspector:"), ("OTInspector", "update:"),
    ("OTInspector", "updateSignal:"), ("OTInspector", "windowShouldClose:"),
    ("OTInspector", "tableView:objectValueForTableColumn:row:"),
    ("OTInspector", "numberOfRowsInTableView:"), ("OTController", "docClose:ask:"),
    ("OTDocView", "deleteGraphicView:"), ("OTDocView", "windowWillClose:"),
    ("OTDocView", "dealloc"), ("OTDocument", "dealloc"),
    ("OTGraphicModel", "dealloc"), ("OTGraphicView", "dealloc"),
]
IVARS = {"OTInspector": ["actInspectorPanel", "selectedGraphicModel", "inspectList"],
         "OTDocView": ["document", "gList"], "OTDocument": ["graphicArray", "docWindow"],
         "OTGraphicView": ["graphicModel"], "OTGraphicModel": ["graphicView"]}

def main():
    raw = APP.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == SHA
    pe = struct.unpack_from("<I", raw, 0x3c)[0]
    assert raw[pe:pe+4] == b"PE\0\0"
    machine, count, timestamp = struct.unpack_from("<HHI", raw, pe+4)
    optsize = struct.unpack_from("<H", raw, pe+20)[0]
    opt = pe+24
    assert machine == 0x14c and struct.unpack_from("<H",raw,opt)[0] == 0x10b
    base = struct.unpack_from("<I", raw, opt+28)[0]
    image_size = struct.unpack_from("<I", raw, opt+56)[0]
    sections = []
    for i in range(count):
        p = opt + optsize + i*40
        size, rva, disk_size, disk = struct.unpack_from("<IIII", raw, p+8)
        sections.append((rva, max(size,disk_size), disk))
    def read_va(va, size):
        rva = va-base
        for begin, length, disk in sections:
            if begin <= rva and rva+size <= begin+length:
                return raw[disk+rva-begin:disk+rva-begin+size]
        raise ValueError(hex(va))
    all_metas = {}
    for path in BANK.glob("modules/*/classes/*/metadata.json"):
        meta = json.loads(path.read_text(encoding="utf-8"))
        if not meta.get("native_class"): continue
        all_metas[meta["native_class"]["class"]] = meta
    derived = {"OTGraphicModel", "OTGraphicView"}
    while True:
        more = {c for c,m in all_metas.items() if m["native_class"]["superclass"] in derived}
        if more <= derived: break
        derived |= more
    extra = []
    for cls in sorted(derived - {"OTGraphicModel", "OTGraphicView"}):
        if any(m["name"] == "dealloc" for m in all_metas[cls]["native_class"]["methods"]):
            extra.append((cls,"dealloc"))
    specs = SPECS + extra
    metas = {c:all_metas[c] for c,_ in specs}
    table_ivars = [v for v in metas["OTInspector"]["native_class"]["ivars"] if v["name"].endswith("TableView")]
    IVARS["OTInspector"] = ["actInspectorPanel", "selectedGraphicModel", "inspectList"] + [v["name"] for v in table_ivars]
    methods = []
    for cls, sel in specs:
        meta = metas[cls]
        all_methods = list(meta["native_class"]["methods"])
        for cat in meta.get("categories", []): all_methods.extend(cat["methods"])
        found = [m for m in all_methods if m["name"] == sel]
        assert len(found) == 1, (cls,sel)
        m = dict(found[0]); m["class"] = cls
        m["rva"] = int(m["imp"],16)-base
        m["prefix"] = read_va(int(m["imp"],16),16).hex()
        methods.append(m)
    classes, ivars = [], []
    for cls, meta in metas.items():
        c = meta["native_class"]
        classes.append(dict(name=cls, rva=int(c["address"],16)-base, size=c["size"]))
        for name in IVARS.get(cls, []):
            iv = next(v for v in c["ivars"] if v["name"] == name)
            ivars.append(dict(iv, **{"class":cls}))
    result = dict(schema=1, original_sha256=SHA, image_base=base, image_size=image_size,
                  timestamp=timestamp, machine=machine, methods=methods, classes=classes,
                  ivars=ivars, extra_dealloc_count=len(extra), note="Static metadata and PE byte contract; no original PE execution.")
    (ROOT/"contract.json").write_text(json.dumps(result,indent=2)+"\n",encoding="ascii")
    lines = ["/* Generated by tools/make_contract.py; original PE was read as bytes only. */",
             '#define IG_SHA256 "'+SHA+'"', '#define IG_IMAGE_BASE 0x%xu'%base,
             '#define IG_IMAGE_SIZE 0x%xu'%image_size, '#define IG_TIMESTAMP 0x%xu'%timestamp,
             'static const IgMethodContract ig_methods[] = {']
    for m in methods:
        prefix = ",".join("0x"+m["prefix"][i:i+2] for i in range(0,32,2))
        lines.append(' {"%s","%s","%s",0x%xu,{%s}},'%(m["class"],m["name"],m["types"],m["rva"],prefix))
    lines += ['};', 'static const IgClassContract ig_classes[] = {']
    for c in classes: lines.append(' {"%s",0x%xu,%du},'%(c["name"],c["rva"],c["size"]))
    lines += ['};', 'static const IgIvarContract ig_ivars[] = {']
    for v in ivars: lines.append(' {"%s","%s",%s,%d},'%(v["class"],v["name"],json.dumps(v["types"]),v["offset"]))
    lines += ['};', '#define IG_METHOD_COUNT %d'%len(methods),
              '#define IG_CLASS_COUNT %d'%len(classes), '#define IG_IVAR_COUNT %d'%len(ivars),
              '#define IG_TABLE_OFFSETS {'+','.join(str(v["offset"]) for v in table_ivars)+'}',
              '#define IG_EXTRA_DEALLOC_LIST(X) '+" ".join("X(%d)"%i for i in range(len(SPECS),len(specs)))]
    (ROOT/"src/contract.inc").write_text("\n".join(lines)+"\n",encoding="ascii")
    print(json.dumps(dict(ok=True, original_pe_execution=False, methods=len(methods), classes=len(classes), ivars=len(ivars))))
if __name__ == "__main__": main()
