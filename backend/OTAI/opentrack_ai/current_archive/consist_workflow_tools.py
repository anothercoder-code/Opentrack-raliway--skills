from typing import Literal
"""Read-only mixed-consist data preview; no save/publish operation is reachable."""
from typing import Any
from pydantic import StrictBool
from .tools import Input, ArchiveTools, sha
from .bundle_tools import Source
from ..errors import APIError

class ConsistSources(Input):
    trains: Source
    depot: Source

class PreviewConsistWorkflow(Input):
    sources: ConsistSources
    spec: dict[str, Any]
    preview_only: Literal[True] = True

class ConsistPreviewTools(ArchiveTools):
    def preview(self, args):
        if args.preview_only is not True:
            raise APIError('PREVIEW_ONLY', 'Only an in-memory preview is supported; no saving or publication pending independent transaction review.')
        from .consist_workflow.core import generate_consist
        blobs = {}; paths = {}
        for key in ConsistSources.model_fields:
            binding = getattr(args.sources, key)
            path = self.path(binding.path)
            blob = self.secure_bytes(path)
            if sha(blob) != binding.sha256:
                raise APIError('SOURCE_CHANGED', 'Source SHA does not match explicit binding', key)
            paths[key] = path; blobs[key] = blob
        try:
            output, receipt = generate_consist(blobs['trains'], blobs['depot'], args.spec)
        except (ValueError, TypeError, KeyError, IndexError, OverflowError) as exc:
            raise APIError('CONSIST_INVALID', 'Outside the explicitly bounded mixed-consist data contract', str(exc)[:500]) from exc
        for key, path in paths.items():
            if self.secure_bytes(path) != blobs[key]:
                raise APIError('SOURCE_CHANGED', 'Source changed during preview', key)
        if type(output) is not bytes or type(receipt) is not dict:
            raise APIError('PREVIEW_MANIFEST', 'Pure generator returned invalid result types')
        if receipt.get('output_sha256') != sha(output) or receipt.get('source_sha256') != {k:sha(b) for k,b in blobs.items()}:
            raise APIError('PREVIEW_MANIFEST', 'Pure generator receipt does not match source/output bytes')
        return {'tool':'opentrack_preview_consist_workflow','preview_only':True,'saved':False,
                'publication_review_pending':True,'native_runtime_ready':False,
                'source_bindings':args.sources.model_dump(),
                'output':{'sha256':sha(output),'bytes':len(output)},'receipt':receipt,
                'limitations':['Static archive generation only; no native dynamics, preparation or runtime acceptance.',
                               'Whole-train braking and resistance follow the explicitly accepted template model, not mass-weighted inference.',
                               'No generated bytes are saved or published by this tool.']}

def tool_definitions(root):
    service = ConsistPreviewTools(root)
    return [('opentrack_preview_consist_workflow',
             'Read-only mixed Engine/Trailer consist data preview from explicitly SHA-bound TrainList and Depot archives. Uses an explicit bounded specification and returns in-memory archive hash plus static resolved length/mass/speed and preservation evidence. No save, publish, inferred brake calibration or native simulation. preview_only=false is rejected before source reads.',
             PreviewConsistWorkflow, service.preview)]
