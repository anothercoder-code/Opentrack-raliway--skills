class ShuntingSources(Input):
    timetable: Source
    courses: Source
    trains: Source
    stations: Source
    connection_template: Source
    depot: Source
class PreviewShuntingConnections(Input):
    sources: ShuntingSources
    spec: dict[str, Any]
    preview_only: Literal[True] = True
class ShuntingPreviewTools(ArchiveTools):
    def preview(self,args):
        if args.preview_only is not True:
            raise APIError('PREVIEW_ONLY','Only an in-memory preview is available; no save or publication.')
        from .shunting_workflow.core import plan_connections
        blobs={};paths={}
        for key in ShuntingSources.model_fields:
            binding=getattr(args.sources,key);path=self.path(binding.path);data=self.secure_bytes(path)
            if sha(data)!=binding.sha256:raise APIError('SOURCE_CHANGED','Source differs from explicit SHA binding',key)
            paths[key]=path;blobs[key]=data
        try:output,receipt=plan_connections(blobs,args.spec)
        except (ValueError,TypeError,KeyError,IndexError,OverflowError)as exc:
            raise APIError('SHUNTING_PLAN_INVALID','Outside the finite split/join timetable-data contract',str(exc)[:500])from exc
        for key,path in paths.items():
            if self.secure_bytes(path)!=blobs[key]:raise APIError('SOURCE_CHANGED','Source changed during preview',key)
        if type(output)is not bytes or type(receipt)is not dict or receipt.get('output_sha256')!=sha(output) or receipt.get('source_sha256')!={k:sha(v)for k,v in blobs.items()}:
            raise APIError('PREVIEW_MANIFEST','Receipt differs from actual source/output bytes')
        return {'tool':'opentrack_preview_shunting_connections','preview_only':True,'saved':False,'publication_review_pending':True,'native_runtime_ready':False,'source_bindings':args.sources.model_dump(),'output':{'sha256':sha(output),'bytes':len(output)},'receipt':receipt,'limitations':['Finite same-day Connection6 split/join planning only; not complete shunting or hump operation.','Initial Train/Course catalogs remain unchanged; resulting composition is a static receipt projection, not persisted runtime state.','Spatial compatibility, native coupling and dynamic composition have not been validated.','No generated bytes are saved or published.']}
def tool_definitions(root):
    service=ShuntingPreviewTools(root)
    return [('opentrack_preview_shunting_connections','Read-only split/join timetable connection preview from six explicit SHA-bound current archives. Checks bounded same-day stop times and component accounting, creates reciprocal Connection6 records in memory, returns output hash and projected composition only. No spatial compatibility, native execution, save or publication. preview_only=false is rejected before source reading.',PreviewShuntingConnections,service.preview)]
